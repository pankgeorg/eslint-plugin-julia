import { tester, plugin } from '../helpers.js';
const bad = (code, ...names) => ({ code, errors: names.map(name => ({ messageId: 'boxed', data: { name } })) });
tester.run('no-reassigned-capture', plugin.rules['no-reassigned-capture'], {
  valid: [
    'f()=(x=1; ()->x)', 'f(x)=()->x',
    'f(x,b)=(if b; x=1; ()->x; end)',
    'f(x,b)=(if b; return 1; else; x=1; ()->x; end)',
    'f(x)=(for i=1:3; x=i; consume(()->x); end)',
    'f(x)=(x=abs(x); ()->x)', 'f(;x=1)=(x=abs(x); ()->x)',
    'f()=(x=1; x=2; x)',
    'f()=(x=1; g=let x=x; ()->x; end; x=2; g)',
    'f()=(x=1; g=(x -> x+1); x=2; g)',
    'f()=[()->i for i=1:3]',
    'f()=[(i+=1; ()->i) for i=1:3]',
    'f(xs)=(for i in xs; local y=i; consume(()->y); end)',
    'f()=(x=[]; g=()->push!(x,1); push!(x,2); g)',
    'f()=(x=1; g=()->(local x=2; x); x=2; g)',
    'x=1; g=()->x; x=2',
    'f()=(x=1; @opaque x; g=()->x; x=2; g)',
    ':(f()=(x=1; g=()->x; x=2; g)); quote; x=1; ()->(x=2); end',
    '@custom function f(); x=1; g=()->x; x=2; g; end',
    'f()=(x=1; g=(i for i=1:x); x=2; g)',
    'f()=(x=1; x=2; Int[x for i=1:3])',
    'f()=(x=1; x=2; Int[x for i=1:3,j=1:3])', // iterable runs outside the generator closure
  ],
  invalid: [
    bad('f()=(x=1; g=()->x; x=2; g)', 'x'),
    bad('f()=(x=1; x=2; ()->x)', 'x'),
    bad('f()=(x=1; g=()->(x+=1); g)', 'x'),
    bad('f()=(local x; g=()->(x=2); g)', 'x'),
    bad('function f(); α=1; read()=α; α=2; read; end', 'α'),
    bad('f(xs)=(x=1; map(xs) do y; x+y; end; x=2)', 'x'),
    bad('f()=(🐱=1; g=()->🐱; h=()->🐱; 🐱=2; (g,h))', '🐱'),
    bad('f(x)=(g=()->x; x=2; g)', 'x'),
    bad('f(x)=(x=1; x=2; ()->x)', 'x'),
    bad('f(x)=(if x<0; x=-x; end; ()->x)', 'x'),
    bad('f(x,b)=(if b; x=1; ()->x; else; ()->x; end)', 'x'),
    bad('f()=(x=1; let x=x; x=2; ()->x; end)', 'x'),
    bad('f()=(x=0; g=(x+i for i=1:3); x=2; g)', 'x'),
    bad('f()=(x=0; g=[x for i=1:3]; x=2; g)', 'x'),
    bad('f()=(x=1; x=2; Function[()->x for i=1:3])', 'x'),
    bad('f()=(x=0; g=(i for i=1:3 if x>0); x=2; g)', 'x'),
    bad('f()=(x=1; x=2; Int[i for i=1:3 if x>0])', 'x'),
    bad('f()=(x=1; x=2; Int[x for i=1:3 if i>0])', 'x'),
    bad('f()=(x=1; x=2; Int[x for i=1:3 for j=1:3])', 'x'),
    bad('f()=(x::Int=1; g=()->x; x=2; g)', 'x'),
    bad('f()=(for i=1:3; g=()->i; i=2; consume(g); end)', 'i'),
    bad('f()=(x=1; g=()->(x=2); h=()->x; (g,h))', 'x'),
  ],
});
